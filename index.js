// Step 2: Manipulating existing elements
// Select the <h1> that has the id of "header" and save it in a variable
const bookStoreTitle = document.querySelector('#header');

// Replace its text with the store's name
bookStoreTitle.textContent = bookStore.name;

// Step 3: Book elements
// Grab the <ul> that will hold every book
const bookList = document.querySelector('#book-list');

// Remove the placeholder <li> from the HTML template (it was only an example)
const placeholder = document.querySelector('#delete-this');
if (placeholder) {
  placeholder.remove();
}

// Loop through every book in the catalog and build its elements
bookStore.books.forEach((book) => {
  // Create the elements for this book
  const bookContainer = document.createElement('li');
  const bookTitle = document.createElement('h3');
  const bookAuthor = document.createElement('p');
  const bookImage = document.createElement('img');

  // Fill them with this book's data
  bookTitle.textContent = book.title;
  bookAuthor.textContent = book.author;
  bookImage.src = book.imageUrl;
  bookImage.alt = `Cover of ${book.title}`;

  // Put the title, author and image inside the <li>
  bookContainer.append(bookTitle, bookAuthor, bookImage);

  // Add the finished <li> to the page
  bookList.appendChild(bookContainer);
});
